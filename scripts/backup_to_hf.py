"""Back up everything needed to rebuild the show to a private Hugging Face dataset.

Layout of the staging folder `DATA_DIR/backup/` (mirrored 1:1 into the dataset):
    audio/<slug>.mp3          every catalog episode, pulled from R2
    catalog/catalog.db        consistent snapshot of the SQLite catalog
    show/                     transcripts/, templates/, excluded_episodes.json from DATA_DIR
    <anything else>           extra folders you place in backup/ are uploaded too
                              (e.g. an archive of episodes from a previous host)

Safe to re-run: unchanged audio is skipped locally, and the Hub deduplicates
uploads so only new or changed data is sent. Requires `hf auth login` and
HF_BACKUP_REPO in .env. Only one run at a time: agents start it in the
background with the `podcast_backup` MCP tool (see core/backup.py).

Usage:
    uv run python scripts/backup_to_hf.py [--steps sync upload] [--repo-id user/name]
"""

import argparse
import logging
import shutil
import sqlite3

from huggingface_hub import HfApi

from core.backup import COMPLETE_MARKER, backup_lock
from core.config import settings
from core.db import CatalogDB
from core.storage import R2StorageClient

logger = logging.getLogger("backup_to_hf")

# Small, high-value folders go first so they're safe even if a large audio upload fails.
UPLOAD_ORDER = ["catalog", "show", "audio"]


def _upload_rank(folder: str) -> tuple[int, str]:
    """Sort key: folders named in UPLOAD_ORDER first (in that order), then any others alphabetically."""
    return (UPLOAD_ORDER.index(folder) if folder in UPLOAD_ORDER else len(UPLOAD_ORDER), folder)


def _dataset_card() -> str:
    """README for the dataset, naming the show it belongs to."""
    return f"""---
license: other
pretty_name: {settings.podcast_title} — private archive
---
# {settings.podcast_title} — private archive

Disaster-recovery copy of the podcast: every episode MP3, the SQLite catalog
(titles, GUIDs, show notes), and show assets. Generated by `scripts/backup_to_hf.py`
in `podcast_server`. Keep this dataset private.
"""


def sync_local_backup() -> dict[str, int]:
    """Refresh DATA_DIR/backup/: pull missing audio from R2, copy show assets, snapshot the catalog."""
    backup = settings.backup_dir
    client = R2StorageClient()
    with CatalogDB(settings.database_path) as db:
        episodes = db.list_episodes()

        downloaded = 0
        for ep in episodes:
            local = backup / "audio" / ep["audio_filename"]
            # Catalog sizes come from R2, so a size match means the local copy is complete.
            if local.exists() and local.stat().st_size == ep["file_size_bytes"]:
                continue
            client.download_file(f"episodes/{ep['audio_filename']}", local)
            downloaded += 1
            logger.info("Pulled %s from R2 (%d new so far)", ep["audio_filename"], downloaded)

        # sqlite's backup API gives a consistent copy even while an agent or the server is writing.
        snapshot_path = backup / "catalog" / "catalog.db"
        snapshot_path.parent.mkdir(parents=True, exist_ok=True)
        with sqlite3.connect(snapshot_path) as snapshot:
            db.conn.backup(snapshot)

    show = backup / "show"
    for folder in (settings.transcripts_dir, settings.templates_dir):
        if folder.exists():
            shutil.copytree(folder, show / folder.name, dirs_exist_ok=True)
    if settings.excluded_episodes_file.exists():
        show.mkdir(parents=True, exist_ok=True)
        shutil.copy2(settings.excluded_episodes_file, show / settings.excluded_episodes_file.name)
    (backup / "README.md").write_text(_dataset_card(), encoding="utf-8")

    logger.info("Local backup ready: %d episodes, %d newly pulled", len(episodes), downloaded)
    return {"episodes": len(episodes), "audio_downloaded": downloaded}


def upload_to_hub(repo_id: str) -> None:
    """Create the private dataset if needed and upload DATA_DIR/backup/, one commit per top-level folder.

    Per-folder commits keep a failure from wasting a multi-GB run, and the Hub's
    chunk-level deduplication makes re-runs skip data that already arrived.
    """
    backup = settings.backup_dir
    api = HfApi()
    api.create_repo(repo_id, repo_type="dataset", private=True, exist_ok=True)
    # Refuse to continue if the dataset somehow exists publicly: the archive may include unreleased material.
    if not api.repo_info(repo_id, repo_type="dataset").private:
        raise RuntimeError(f"{repo_id} is public; make it private before uploading the archive.")

    api.upload_file(repo_id=repo_id, repo_type="dataset", path_or_fileobj=backup / "README.md", path_in_repo="README.md")
    # Every top-level folder is uploaded, so extra archives placed in backup/ are included automatically.
    folders = sorted((p.name for p in backup.iterdir() if p.is_dir() and not p.name.startswith(".")), key=_upload_rank)
    for folder in folders:
        api.upload_folder(
            repo_id=repo_id,
            repo_type="dataset",
            folder_path=backup / folder,
            path_in_repo=folder,
            commit_message=f"backup: sync {folder}/",
            ignore_patterns=["*.part", "*.tmp", "*.mp3.*"],  # *.mp3.<hex> = boto3 temp files from interrupted downloads
        )
        logger.info("Uploaded %s/", folder)
    logger.info("%s: https://huggingface.co/datasets/%s", COMPLETE_MARKER, repo_id)


def main() -> None:
    """Run the requested backup steps in order."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--steps", nargs="+", choices=["sync", "upload"], default=["sync", "upload"])
    parser.add_argument("--repo-id", default=settings.hf_backup_repo)
    args = parser.parse_args()
    if "upload" in args.steps and not args.repo_id:
        parser.error("set HF_BACKUP_REPO in .env or pass --repo-id")
    # One run at a time, whether started by hand or by the podcast_backup MCP tool.
    with backup_lock():
        if "sync" in args.steps:
            sync_local_backup()
        if "upload" in args.steps:
            upload_to_hub(args.repo_id)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    main()
